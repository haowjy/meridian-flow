import { buildDocumentSchema,createCollabYDoc } from '@meridian/prosemirror-schema';
import { writeBlocks } from '@meridian/agent-edit/diff';
import { getTopLevelXmlBlocks,getBlockItemId,blockItemIdKey } from '@meridian/agent-edit/integration';
import { initProseMirrorDoc,updateYFragment } from 'y-prosemirror';
import { createRequire } from 'node:module';
const req=createRequire(import.meta.url); const yreq=createRequire(req.resolve('y-prosemirror')); const {EditorState}=yreq('prosemirror-state');
import * as Y from 'yjs';
import { seedDraftState } from '../domain/draft-content.js';
const schema=buildDocumentSchema(), d=createCollabYDoc({gc:false}), f=d.getXmlFragment('prosemirror');
writeBlocks(f,schema,[schema.nodes.paragraph.create(null,schema.text('sticky note'))]);
d.getMap('board-layout').set('note',{x:99,y:77});
const ids=()=>getTopLevelXmlBlocks(d).map(b=>blockItemIdKey(getBlockItemId(b)));
const seed=seedDraftState(d,'room',1); const attribution=createCollabYDoc({gc:false}); Y.applyUpdate(attribution,seed.seed!.liveAttribution.state);
console.log('seed attribution layout',JSON.stringify(attribution.getMap('board-layout').toJSON()));
let binding=initProseMirrorDoc(f,schema); let state=EditorState.create({doc:binding.doc});
console.log('before split',JSON.stringify({ids:ids(),text:state.doc.textContent}));
state=state.apply(state.tr.split(7)); updateYFragment(d,f,state.doc,binding.meta);
console.log('after split',JSON.stringify({ids:ids(),text:state.doc.toJSON()}));
state=state.apply(state.tr.join(8)); updateYFragment(d,f,state.doc,binding.meta);
console.log('after join',JSON.stringify({ids:ids(),text:state.doc.toJSON()}));
